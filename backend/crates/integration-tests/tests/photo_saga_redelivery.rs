/// Poll `projection_photo` until the photo has converged to the fully
/// processed state: version 4 (`PhotoUploaded` + `OriginalNormalized` +
/// `VariantGenerated` thumb + `VariantGenerated` medium) with both variants
/// `Ready`. Retries on `NotFound` and lagging versions within the deadline.
async fn await_photo_converged(
    repo: &PhotoRepositoryImpl,
    photo_id: PhotoId,
    deadline: tokio::time::Instant,
) -> Result<PhotoView> {
    loop {
        let view = repo.find_by_id(photo_id).await;
        let converged = view.as_ref().is_ok_and(|v| {
            v.version == AggregateVersion(4)
                && variant_ready(v, PhotoVariant::Thumb)
                && variant_ready(v, PhotoVariant::Medium)
        });
        if converged {
            return Ok(view.expect("found, proven by converged"));
        }
        if tokio::time::Instant::now() > deadline {
            anyhow::bail!(
                "Timed out waiting for photo projection to converge; last: {:?}",
                view.err()
            );
        }
        tokio::time::sleep(Duration::from_millis(200)).await;
    }
}

fn variant_ready(view: &PhotoView, kind: PhotoVariant) -> bool {
    view.variants
        .iter()
        .any(|v| v.kind == kind && v.status == VariantStatus::Ready)
}

/// The `PhotoUploaded` event a `PhotoThumbnailSaga` receives for a photo.
fn uploaded_event(
    photo_id: PhotoId,
    content_type: &str,
    size_bytes: u64,
    binding: PhotoBinding,
    series_id: Option<SeriesId>,
) -> Event<PhotoEvent, EventMetadata> {
    Event {
        id: Uuid::now_v7(),
        partition_key: Uuid::now_v7(),
        partition_id: 0,
        transaction_id: Uuid::nil(),
        partition_sequence: 0,
        stream_version: 0,
        stream_id: StreamId::new_from_parts(PhotoAggregate::category(), photo_id.to_string()),
        name: "PhotoUploaded".to_string(),
        data: PhotoEvent::PhotoUploaded {
            id: photo_id,
            content_type: content_type.to_string(),
            size_bytes,
            variant_statuses: vec![
                (PhotoVariant::Original, VariantStatus::Pending),
                (PhotoVariant::Thumb, VariantStatus::Pending),
                (PhotoVariant::Medium, VariantStatus::Pending),
            ],
            binding,
            version: AggregateVersion::INITIAL,
        },
        metadata: Metadata {
            causation_command: None,
            causation_event: None,
            data: Some(EventMetadata {
                actor: None,
                provenance: Provenance::Saga("photo_saga_redelivery_test".to_string()),
                series_id,
            }),
        },
        timestamp: chrono::Utc::now(),
    }
}

#[tokio::test]
async fn thumbnail_saga_redelivery_is_idempotent_and_converges() -> Result<()> {
    // Start all three tiers: Postgres (projection), SierraDB (event store),
    // Garage (photo bytes).
    let (pg_pool, _pg_guard) = spawn_postgres().await?;
    let (sierra_client, _conn, _sierra_guard) = spawn_sierradb().await?;
    let (creds, _garage_guard) = spawn_garage().await?;

    let storage = build_storage(&creds);
    let cmd_service = {
        let conn = sierra_client.get_multiplexed_async_connection().await?;
        CommandService::new(conn)
    };
    let photo_repo = PhotoRepositoryImpl::new(pg_pool.clone());
    let photo_commands = infra::event_store::PhotoCommandsImpl::new(cmd_service.clone());

    // Spawn the photo projector so the projection reflects the events.
    let redis_client = Arc::clone(&sierra_client);
    let _photo_projector = infra::projectors::spawn_photo_projector(
        pg_pool.clone(),
        Arc::clone(&redis_client),
        infra::projectors::ProjectorFlushConfig::test_profile(),
    )
    .await?;

    // Store the original bytes and upload the photo (writes `PhotoUploaded`).
    let photo_id = PhotoId::new();
    let content_type = "image/jpeg".to_string();
    storage
        .store(
            photo_id,
            PhotoVariant::Original,
            TINY_JPEG.to_vec(),
            content_type.clone(),
        )
        .await?;

    let binding = PhotoBinding::Costume {
        costume_id: Uuid::now_v7(),
    };
    let series_id = Some(SeriesId::new());
    let _uploaded_version = photo_commands
        .upload(
            test_user(),
            UploadPhoto {
                id: photo_id,
                content_type: content_type.clone(),
                size_bytes: TINY_JPEG.len() as u64,
                binding: binding.clone(),
                series_id,
            },
        )
        .await?;

    let event = uploaded_event(
        photo_id,
        &content_type,
        TINY_JPEG.len() as u64,
        binding,
        series_id,
    );
    let mut saga = PhotoThumbnailSaga::new(cmd_service.clone(), storage.clone());

    // ── 1st delivery: normalise + generate thumb/medium. ───────────────────
    saga.handle(&mut (), photo_id, event.clone())
        .await
        .map_err(|e| anyhow::anyhow!("first delivery failed: {e}"))?;

    let deadline = tokio::time::Instant::now() + Duration::from_secs(30);
    let converged = await_photo_converged(&photo_repo, photo_id, deadline).await?;
    assert_eq!(
        converged.version,
        AggregateVersion(4),
        "full saga run must advance the photo to version 4"
    );
    assert_eq!(
        converged.content_type, content_type,
        "content_type is preserved"
    );
    assert!(
        converged.size_bytes > 0,
        "projection_photo.size_bytes must be real once the saga completes"
    );
    assert!(variant_ready(&converged, PhotoVariant::Thumb));
    assert!(variant_ready(&converged, PhotoVariant::Medium));
    for v in &converged.variants {
        if v.kind != PhotoVariant::Original {
            assert!(
                v.size_bytes > 0,
                "generated variant {:?} must carry a real size",
                v.kind
            );
        }
    }

    // ── 2nd delivery: replay `PhotoUploaded` AFTER the aggregate advanced. ──
    // This used to crash-loop with `expected AggregateVersion(1), current
    // AggregateVersion(2)` (issue #515); it must now be an idempotent no-op.
    saga.handle(&mut (), photo_id, event)
        .await
        .map_err(|e| anyhow::anyhow!("redelivery failed: {e}"))?;

    let converged_after_redelivery = await_photo_converged(&photo_repo, photo_id, deadline).await?;
    assert_eq!(
        converged_after_redelivery.version,
        AggregateVersion(4),
        "redelivery must not advance the aggregate or append duplicate events"
    );
    assert!(variant_ready(
        &converged_after_redelivery,
        PhotoVariant::Thumb
    ));
    assert!(variant_ready(
        &converged_after_redelivery,
        PhotoVariant::Medium
    ));

    Ok(())
}
